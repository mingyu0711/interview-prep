    await user.click(screen.getByRole('button', { name: '프론트엔드 (1)' }))
    await user.click(screen.getByRole('button', { name: '전체 (2)' }))
    expect(item('자기소개').getByRole('alert')).toHaveTextContent('다시 시도')
    expect(requests.mock.calls.filter(([request]) => request.method === 'DELETE')).toHaveLength(0)
    await user.click(item('자기소개').getByRole('button', { name: '삭제' }))
